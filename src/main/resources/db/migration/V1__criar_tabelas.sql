-- ============================================================
-- V1 - Criação das tabelas do Sistema de Chamado
-- Datas em TIMESTAMP (sem fuso), sempre gravadas no horário de
-- America/Sao_Paulo (fuso fixado na aplicação).
-- ============================================================

-- ------------------------------------------------------------
-- Áreas de atendimento (TI, Manutenção)
-- ------------------------------------------------------------
CREATE TABLE area (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome    VARCHAR(80)  NOT NULL,
    sigla   VARCHAR(10)  NOT NULL,
    ativo   BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_area_nome  UNIQUE (nome),
    CONSTRAINT uk_area_sigla UNIQUE (sigla),
    CONSTRAINT ck_area_sigla CHECK (sigla ~ '^[A-Z]{2,10}$')
);

-- ------------------------------------------------------------
-- Categorias de cada área
-- ------------------------------------------------------------
CREATE TABLE categoria (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id  BIGINT       NOT NULL,
    nome     VARCHAR(100) NOT NULL,
    ativo    BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_categoria_area FOREIGN KEY (area_id) REFERENCES area (id),
    CONSTRAINT uk_categoria_area_nome UNIQUE (area_id, nome),
    -- Permite que o chamado garanta que a categoria pertence à mesma área
    CONSTRAINT uk_categoria_id_area UNIQUE (id, area_id)
);

CREATE INDEX ix_categoria_area ON categoria (area_id);

-- ------------------------------------------------------------
-- Setores do clube (de onde vem o solicitante)
-- ------------------------------------------------------------
CREATE TABLE setor (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome   VARCHAR(100) NOT NULL,
    ativo  BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_setor_nome UNIQUE (nome)
);

-- ------------------------------------------------------------
-- Locais físicos (onde está o problema)
-- ------------------------------------------------------------
CREATE TABLE local (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome   VARCHAR(100) NOT NULL,
    ativo  BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_local_nome UNIQUE (nome)
);

-- ------------------------------------------------------------
-- Usuários com login (atendente, gestor, admin)
-- ------------------------------------------------------------
CREATE TABLE usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(120) NOT NULL,
    email       VARCHAR(150) NOT NULL,
    senha_hash  VARCHAR(100) NOT NULL,
    perfil      VARCHAR(20)  NOT NULL,
    area_id     BIGINT,
    ativo       BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_usuario_area FOREIGN KEY (area_id) REFERENCES area (id),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('ATENDENTE', 'GESTOR', 'ADMIN')),
    -- Atendente e gestor sempre pertencem a uma área; admin pode não ter área
    CONSTRAINT ck_usuario_area_obrigatoria CHECK (perfil = 'ADMIN' OR area_id IS NOT NULL),
    CONSTRAINT ck_usuario_email_minusculo CHECK (email = LOWER(email))
);

CREATE UNIQUE INDEX uk_usuario_email ON usuario (email);
CREATE INDEX ix_usuario_area ON usuario (area_id);

-- ------------------------------------------------------------
-- Prazos de SLA por área e prioridade (em minutos)
-- ------------------------------------------------------------
CREATE TABLE sla_config (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id                    BIGINT      NOT NULL,
    prioridade                 VARCHAR(20) NOT NULL,
    minutos_primeira_resposta  INTEGER     NOT NULL,
    minutos_resolucao          INTEGER     NOT NULL,
    CONSTRAINT fk_sla_config_area FOREIGN KEY (area_id) REFERENCES area (id),
    CONSTRAINT uk_sla_config_area_prioridade UNIQUE (area_id, prioridade),
    CONSTRAINT ck_sla_config_prioridade CHECK (prioridade IN ('CRITICA', 'ALTA', 'MEDIA', 'BAIXA')),
    CONSTRAINT ck_sla_config_minutos CHECK (
        minutos_primeira_resposta > 0
        AND minutos_resolucao > 0
        AND minutos_resolucao >= minutos_primeira_resposta
    )
);

-- ------------------------------------------------------------
-- Chamados
-- ------------------------------------------------------------
CREATE TABLE chamado (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocolo                VARCHAR(20)  NOT NULL,
    area_id                  BIGINT       NOT NULL,
    categoria_id             BIGINT       NOT NULL,
    setor_id                 BIGINT       NOT NULL,
    local_id                 BIGINT       NOT NULL,
    solicitante_nome         VARCHAR(120) NOT NULL,
    solicitante_email        VARCHAR(150),
    solicitante_telefone     VARCHAR(20),
    solicitante_matricula    VARCHAR(30),
    titulo                   VARCHAR(150) NOT NULL,
    descricao                TEXT         NOT NULL,
    urgencia                 VARCHAR(20)  NOT NULL,
    prioridade               VARCHAR(20)  NOT NULL,
    status                   VARCHAR(20)  NOT NULL DEFAULT 'ABERTO',
    atendente_id             BIGINT,
    data_abertura            TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    data_primeira_resposta   TIMESTAMP,
    data_resolucao           TIMESTAMP,
    data_fechamento          TIMESTAMP,
    prazo_primeira_resposta  TIMESTAMP,
    prazo_resolucao          TIMESTAMP,
    CONSTRAINT uk_chamado_protocolo UNIQUE (protocolo),
    CONSTRAINT fk_chamado_area      FOREIGN KEY (area_id)      REFERENCES area (id),
    CONSTRAINT fk_chamado_setor     FOREIGN KEY (setor_id)     REFERENCES setor (id),
    CONSTRAINT fk_chamado_local     FOREIGN KEY (local_id)     REFERENCES local (id),
    CONSTRAINT fk_chamado_atendente FOREIGN KEY (atendente_id) REFERENCES usuario (id),
    -- A categoria precisa ser da mesma área do chamado
    CONSTRAINT fk_chamado_categoria_area FOREIGN KEY (categoria_id, area_id)
        REFERENCES categoria (id, area_id),
    -- Formato ÁREA-ANO-XXXX sem caracteres ambíguos (0, O, 1, I, L)
    CONSTRAINT ck_chamado_protocolo CHECK (
        protocolo ~ '^[A-Z]{2,10}-[0-9]{4}-[2-9A-HJKMNP-Z]{4}$'
    ),
    CONSTRAINT ck_chamado_urgencia   CHECK (urgencia   IN ('BAIXA', 'MEDIA', 'ALTA')),
    CONSTRAINT ck_chamado_prioridade CHECK (prioridade IN ('BAIXA', 'MEDIA', 'ALTA', 'CRITICA')),
    CONSTRAINT ck_chamado_status     CHECK (status IN (
        'ABERTO', 'EM_ATENDIMENTO', 'AGUARDANDO', 'RESOLVIDO', 'FECHADO', 'REABERTO'
    ))
);

CREATE INDEX ix_chamado_status        ON chamado (status);
CREATE INDEX ix_chamado_area          ON chamado (area_id);
CREATE INDEX ix_chamado_atendente     ON chamado (atendente_id);
CREATE INDEX ix_chamado_data_abertura ON chamado (data_abertura);
CREATE INDEX ix_chamado_categoria     ON chamado (categoria_id);

-- ------------------------------------------------------------
-- Histórico do chamado (comentários, respostas, mudanças)
-- ------------------------------------------------------------
CREATE TABLE chamado_interacao (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chamado_id       BIGINT      NOT NULL,
    autor_id         BIGINT,
    tipo             VARCHAR(30) NOT NULL,
    texto            TEXT,
    interno          BOOLEAN     NOT NULL DEFAULT FALSE,
    status_anterior  VARCHAR(20),
    status_novo      VARCHAR(20),
    data             TIMESTAMP   NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT fk_interacao_chamado FOREIGN KEY (chamado_id) REFERENCES chamado (id) ON DELETE CASCADE,
    CONSTRAINT fk_interacao_autor   FOREIGN KEY (autor_id)   REFERENCES usuario (id),
    CONSTRAINT ck_interacao_tipo CHECK (tipo IN (
        'COMENTARIO', 'RESPOSTA_SOLICITANTE', 'MUDANCA_STATUS', 'ATRIBUICAO'
    )),
    CONSTRAINT ck_interacao_status_anterior CHECK (status_anterior IS NULL OR status_anterior IN (
        'ABERTO', 'EM_ATENDIMENTO', 'AGUARDANDO', 'RESOLVIDO', 'FECHADO', 'REABERTO'
    )),
    CONSTRAINT ck_interacao_status_novo CHECK (status_novo IS NULL OR status_novo IN (
        'ABERTO', 'EM_ATENDIMENTO', 'AGUARDANDO', 'RESOLVIDO', 'FECHADO', 'REABERTO'
    )),
    -- Mudança de status precisa informar o status novo
    CONSTRAINT ck_interacao_mudanca_status CHECK (tipo <> 'MUDANCA_STATUS' OR status_novo IS NOT NULL)
);

CREATE INDEX ix_interacao_chamado ON chamado_interacao (chamado_id, data);

-- ------------------------------------------------------------
-- Anexos do chamado (arquivo fica em disco; aqui só os metadados)
-- ------------------------------------------------------------
CREATE TABLE anexo (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chamado_id     BIGINT       NOT NULL,
    nome_original  VARCHAR(255) NOT NULL,
    caminho        VARCHAR(500) NOT NULL,
    tipo_mime      VARCHAR(100) NOT NULL,
    tamanho        BIGINT       NOT NULL,
    data           TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT fk_anexo_chamado FOREIGN KEY (chamado_id) REFERENCES chamado (id) ON DELETE CASCADE,
    CONSTRAINT uk_anexo_caminho UNIQUE (caminho),
    CONSTRAINT ck_anexo_tamanho CHECK (tamanho >= 0)
);

CREATE INDEX ix_anexo_chamado ON anexo (chamado_id);
