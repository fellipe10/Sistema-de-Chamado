-- ------------------------------------------------------------
-- 1) Expediente de cada área
--    Um dia pode ter mais de um período (ex.: manhã e tarde).
--    dia_semana segue a ISO-8601: 1 = segunda ... 7 = domingo.
--    Dia sem nenhuma linha = dia sem expediente (o prazo não conta).
-- ------------------------------------------------------------
CREATE TABLE expediente (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id      BIGINT  NOT NULL,
    dia_semana   INTEGER NOT NULL,
    hora_inicio  TIME    NOT NULL,
    hora_fim     TIME    NOT NULL,
    CONSTRAINT fk_expediente_area FOREIGN KEY (area_id) REFERENCES area (id),
    CONSTRAINT ck_expediente_dia CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT ck_expediente_horas CHECK (hora_fim > hora_inicio),
    CONSTRAINT uk_expediente_periodo UNIQUE (area_id, dia_semana, hora_inicio)
);

CREATE INDEX ix_expediente_area ON expediente (area_id);

-- Padrão para as áreas existentes (TI e Manutenção):
-- segunda a sexta, 08:00–12:00 e 13:00–17:00 = 8 h úteis por dia (1 dia útil = 480 min).
INSERT INTO expediente (area_id, dia_semana, hora_inicio, hora_fim)
SELECT a.id, d.dia, p.inicio, p.fim
  FROM area a
 CROSS JOIN generate_series(1, 5) AS d(dia)
 CROSS JOIN (VALUES (TIME '08:00', TIME '12:00'),
                    (TIME '13:00', TIME '17:00')) AS p(inicio, fim)
 ORDER BY a.id, d.dia, p.inicio;

-- ------------------------------------------------------------
-- 2) Feriados
--    area_id NULL = vale para todas as áreas.
--    Pontos facultativos (Carnaval, Quarta de Cinzas, Corpus Christi...) NÃO entram aqui:
--    o admin cadastra depois (Etapa 5), se o clube parar nesses dias.
-- ------------------------------------------------------------
CREATE TABLE feriado (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data       DATE         NOT NULL,
    descricao  VARCHAR(100) NOT NULL,
    area_id    BIGINT,
    CONSTRAINT fk_feriado_area FOREIGN KEY (area_id) REFERENCES area (id)
);

-- Mesma data não pode ser cadastrada duas vezes para o mesmo alcance (todas as áreas ou uma área).
CREATE UNIQUE INDEX uk_feriado_data_area ON feriado (data, COALESCE(area_id, 0));
CREATE INDEX ix_feriado_data ON feriado (data);

